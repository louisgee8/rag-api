"""
FastAPI app entrypoint.

Phase 1 / Step 5 — adds POST /query/retrieve and POST /query/answer.

Routes:
- GET  /health           — liveness probe
- POST /ingest           — JSON body: {source, text, metadata?}
- POST /ingest/file      — multipart: file=, source=
- POST /query/retrieve   — JSON body: {question, top_k?} -> raw chunks
- POST /query/answer     — JSON body: {question, top_k?} -> LLM-synthesized answer
- GET  /docs             — auto-generated by FastAPI
"""

from typing import Any

import anthropic
from fastapi import Depends, FastAPI, File, Form, HTTPException, UploadFile
from pydantic import BaseModel, Field

from app import ingest as ingest_lib, retrieval as retrieval_lib, synthesis as synthesis_lib
from app.auth import TenantIdentity
from app.security import audit
from app.security.injection import InjectionDetectedError, scan_or_raise as injection_scan_or_raise
from app.security.pii import PIIDetectedError
from app.security.ratelimit import enforce_rate_limit
from app.security.relevance import LowConfidenceError, evaluate_or_raise as relevance_evaluate_or_raise

app = FastAPI(
    title="rag-api",
    description=(
        "Retrieval-Augmented Generation API. "
        "Phase 2 Step 6 — structured audit logging "
        "(JSONL on stdout for every security-relevant event)."
    ),
    version="0.11.0",
)


# --------------------------------------------------------------------------
# Schemas
# --------------------------------------------------------------------------

class IngestTextRequest(BaseModel):
    """JSON body for POST /ingest. Pydantic enforces non-empty source/text."""
    source: str = Field(..., min_length=1, max_length=512,
                        description="Canonical doc id. Re-ingest replaces by source.")
    text: str = Field(..., min_length=1,
                      description="Raw text to chunk + embed.")
    metadata: dict[str, Any] | None = Field(default=None,
                                            description="Arbitrary JSONB metadata.")


class IngestResponse(BaseModel):
    """Standard response shape for both ingest paths."""
    source: str
    chunks_created: int
    chunks_replaced: int  # rows wiped by DELETE-by-source step


class QueryRequest(BaseModel):
    """JSON body shared by /query/retrieve and /query/answer."""
    question: str = Field(..., min_length=1, max_length=2000,
                          description="Natural-language query.")
    top_k: int | None = Field(default=None, ge=1, le=50,
                              description="Override env-default top-K.")


class RetrievedChunkOut(BaseModel):
    """Wire-format for one retrieved chunk."""
    source: str
    chunk_text: str
    distance: float  # cosine distance, lower = more similar


class QueryRetrieveResponse(BaseModel):
    """Response for /query/retrieve — raw chunks, no LLM."""
    question: str
    top_k: int
    chunks: list[RetrievedChunkOut]


class QueryAnswerResponse(BaseModel):
    """Response for /query/answer — LLM-synthesized answer + provenance."""
    question: str
    answer: str
    model: str
    top_k: int
    chunks_used: list[RetrievedChunkOut]
    input_tokens: int
    output_tokens: int


# --------------------------------------------------------------------------
# Routes
# --------------------------------------------------------------------------

@app.get("/health", tags=["meta"])
def health() -> dict:
    """Liveness probe. Returns 200 if the FastAPI process is up."""
    return {"status": "ok", "service": "rag-api", "version": app.version}


@app.post("/ingest", response_model=IngestResponse, tags=["ingest"])
def ingest_text_endpoint(
    payload: IngestTextRequest,
    identity: TenantIdentity = Depends(enforce_rate_limit),
) -> IngestResponse:
    """
    Ingest raw text via JSON body.

    Pydantic validates source/text non-empty BEFORE the handler runs;
    malformed payloads return 422 automatically.

    PII detection (Phase 2 Step 3): SSN / email / US phone / Luhn-valid CC
    in the text body -> 400 with {"detail": {"error": "pii_detected",
    "kinds": [{"kind": "ssn", "count": N}, ...]}}. Values never echoed.

    Indirect prompt injection (Phase 2 Step 4): jailbreak phrases in the
    text body -> 400 with {"detail": {"error": "prompt_injection_detected",
    "kinds": [{"kind": "override", "count": N}, ...]}}. Same hard-reject
    contract as PII.

    Phase 2 Step 6: emits ingest.success / pii.detected / injection.detected
    audit events, correlated via identity.request_id.
    """
    try:
        result = ingest_lib.ingest_text(
            source=payload.source,
            text=payload.text,
            metadata=payload.metadata,
        )
    except InjectionDetectedError as e:
        audit.emit(
            audit.EVT_INJECTION_DETECTED,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            kinds=e.summary,
            route="/ingest",
        )
        raise HTTPException(
            status_code=400,
            detail={"error": "prompt_injection_detected", "kinds": e.summary},
        )
    except PIIDetectedError as e:
        audit.emit(
            audit.EVT_PII_DETECTED,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            kinds=e.summary,
            route="/ingest",
        )
        raise HTTPException(
            status_code=400,
            detail={"error": "pii_detected", "kinds": e.summary},
        )

    audit.emit(
        audit.EVT_INGEST_SUCCESS,
        key_prefix=identity.key_prefix,
        tenant=identity.tenant_id,
        request_id=identity.request_id,
        source=result.source,
        chunks_created=result.chunks_created,
        chunks_replaced=result.chunks_replaced,
        route="/ingest",
    )
    return IngestResponse(
        source=result.source,
        chunks_created=result.chunks_created,
        chunks_replaced=result.chunks_replaced,
    )


@app.post("/ingest/file", response_model=IngestResponse, tags=["ingest"])
def ingest_file_endpoint(
    source: str = Form(..., min_length=1, max_length=512),
    file: UploadFile = File(...),
    identity: TenantIdentity = Depends(enforce_rate_limit),
) -> IngestResponse:
    """
    Ingest a file (PDF or text) via multipart upload.

    Form fields:
    - source: canonical id for this doc (used for re-ingest)
    - file: must be application/pdf or text/plain, <= 10MB

    Mime/size violations -> 400 (caught from ValueError in ingest_lib).
    Indirect prompt injection -> 400 (Step 4, same contract as /ingest).

    Phase 2 Step 6: emits ingest.success / pii.detected / injection.detected
    audit events, correlated via identity.request_id.
    """
    # file.file is the underlying SpooledTemporaryFile (sync read is fine
    # because this is a sync handler running in FastAPI's thread pool).
    file_bytes = file.file.read()
    try:
        result = ingest_lib.ingest_file(
            source=source,
            file_bytes=file_bytes,
            content_type=file.content_type or "",
        )
    except InjectionDetectedError as e:
        audit.emit(
            audit.EVT_INJECTION_DETECTED,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            kinds=e.summary,
            route="/ingest/file",
        )
        raise HTTPException(
            status_code=400,
            detail={"error": "prompt_injection_detected", "kinds": e.summary},
        )
    except PIIDetectedError as e:
        # Phase 2 Step 3: same rejection contract as /ingest JSON path.
        audit.emit(
            audit.EVT_PII_DETECTED,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            kinds=e.summary,
            route="/ingest/file",
        )
        raise HTTPException(
            status_code=400,
            detail={"error": "pii_detected", "kinds": e.summary},
        )
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    audit.emit(
        audit.EVT_INGEST_SUCCESS,
        key_prefix=identity.key_prefix,
        tenant=identity.tenant_id,
        request_id=identity.request_id,
        source=result.source,
        chunks_created=result.chunks_created,
        chunks_replaced=result.chunks_replaced,
        route="/ingest/file",
    )
    return IngestResponse(
        source=result.source,
        chunks_created=result.chunks_created,
        chunks_replaced=result.chunks_replaced,
    )


@app.post("/query/retrieve", response_model=QueryRetrieveResponse, tags=["query"])
def query_retrieve_endpoint(
    payload: QueryRequest,
    identity: TenantIdentity = Depends(enforce_rate_limit),
) -> QueryRetrieveResponse:
    """
    Retrieve top-K chunks most similar to `question`. No LLM call.

    Cheap path (no Anthropic tokens spent) — useful for debugging
    retrieval quality and for clients that want their own composition
    layer on top of raw chunks.
    """
    try:
        chunks = retrieval_lib.retrieve(
            question=payload.question,
            top_k=payload.top_k,
        )
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    return QueryRetrieveResponse(
        question=payload.question,
        top_k=len(chunks),
        chunks=[
            RetrievedChunkOut(
                source=c.source,
                chunk_text=c.chunk_text,
                distance=c.distance,
            )
            for c in chunks
        ],
    )


@app.post("/query/answer", response_model=QueryAnswerResponse, tags=["query"])
def query_answer_endpoint(
    payload: QueryRequest,
    identity: TenantIdentity = Depends(enforce_rate_limit),
) -> QueryAnswerResponse:
    """
    Retrieve top-K chunks AND synthesize an answer via Anthropic.

    Failure modes mapped to HTTP:
    - prompt injection in question  -> 400 (Phase 2 Step 4 direct defense)
    - empty/invalid question        -> 400
    - low retrieval confidence      -> 422 (Phase 2 Step 5 relevance gate)
    - Anthropic auth failure        -> 502 (upstream auth, not our auth)
    - Anthropic rate limit/timeout  -> 504
    - Other Anthropic API errors    -> 502

    Phase 2 Step 4 (direct prompt injection): scans the user's question
    against the jailbreak blocklist BEFORE retrieval. Rejection happens
    upstream of the embed call and the LLM call — saves both compute and
    risk surface. Structural defense (fenced context + hardened system
    prompt) lives in app.synthesis and runs unconditionally on the chunks
    that make it past retrieval.

    Phase 2 Step 5 (relevance threshold): after retrieval, checks the
    cosine-distance gap between hit #1 and hit #2. If the gap is below
    RELEVANCE_MIN_GAP, returns 422 {"error": "low_confidence", ...} and
    never calls Anthropic. Cheap path for "you asked something the corpus
    can't answer" — refuses to hallucinate instead of guessing. Only
    enforced on /query/answer; /query/retrieve stays raw so clients can
    still inspect low-confidence results to debug their corpus.
    """
    try:
        injection_scan_or_raise(payload.question)
    except InjectionDetectedError as e:
        # Direct prompt injection on the question itself. Audit + reject.
        audit.emit(
            audit.EVT_INJECTION_DETECTED,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            kinds=e.summary,
            route="/query/answer",
            site="question",
        )
        raise HTTPException(
            status_code=400,
            detail={"error": "prompt_injection_detected", "kinds": e.summary},
        )

    try:
        chunks = retrieval_lib.retrieve(
            question=payload.question,
            top_k=payload.top_k,
        )
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))

    # Phase 2 Step 5: relevance gate. Short-circuits BEFORE the Anthropic
    # call so a low-confidence query doesn't burn tokens.
    try:
        relevance_evaluate_or_raise(chunks)
    except LowConfidenceError as e:
        # Phase 2 Step 6: audit the gate fire. Carries reason + gap +
        # threshold so the SIEM can spot a tenant with a chronically
        # mis-tuned corpus (mostly insufficient_gap) vs one starved of
        # documents (mostly single_candidate / empty_result).
        audit.emit(
            audit.EVT_RELEVANCE_LOW_CONFIDENCE,
            key_prefix=identity.key_prefix,
            tenant=identity.tenant_id,
            request_id=identity.request_id,
            reason=e.reason,
            chunks_returned=e.chunks_returned,
            top_distance=e.top_distance,
            gap=e.gap,
            threshold=e.threshold,
        )
        raise HTTPException(status_code=422, detail=e.envelope)

    try:
        result = synthesis_lib.synthesize(
            question=payload.question,
            chunks=chunks,
        )
    except anthropic.AuthenticationError as e:
        raise HTTPException(status_code=502, detail=f"Anthropic auth failed: {e}")
    except (anthropic.APITimeoutError, anthropic.RateLimitError) as e:
        raise HTTPException(status_code=504, detail=f"Anthropic upstream slow: {e}")
    except anthropic.APIError as e:
        raise HTTPException(status_code=502, detail=f"Anthropic upstream error: {e}")

    audit.emit(
        audit.EVT_QUERY_ANSWER_SUCCESS,
        key_prefix=identity.key_prefix,
        tenant=identity.tenant_id,
        request_id=identity.request_id,
        chunks_used=len(result.chunks_used),
        input_tokens=result.input_tokens,
        output_tokens=result.output_tokens,
        model=result.model,
    )
    return QueryAnswerResponse(
        question=payload.question,
        answer=result.answer,
        model=result.model,
        top_k=len(result.chunks_used),
        chunks_used=[
            RetrievedChunkOut(
                source=c.source,
                chunk_text=c.chunk_text,
                distance=c.distance,
            )
            for c in result.chunks_used
        ],
        input_tokens=result.input_tokens,
        output_tokens=result.output_tokens,
    )
